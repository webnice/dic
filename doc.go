/*
Пакет dic — библиотека справочников.

Справочники реализованы таким образом, чтобы их можно было дополнять
пользовательскими данными через встраивание. Получившийся пользовательский
справочник обладает всеми свойствами справочника библиотеки и принимается
теми же функциями, которые используют исходный справочник.

# Справочники

  - Mime — справочник MIME типов.
  - Method — справочник HTTP методов запросов.
  - Header — справочник заголовков.
  - Status — справочник статусов HTTP ответов.
  - File — справочник MIME типов расширений имён файлов.
  - Error — справочник ошибок.

# MIME типы

Справочник MIME типов содержит предопределённые типы с описанием. Объект MIME
типа предоставляет доступ к основному типу, подтипу и опциям, а так же
сравнение типов без учёта и с учётом опций:

	m := dic.Mime().ApplicationJson
	m.Main()   // "application"
	m.Sub()    // "json"
	m.Charset() // "utf-8"
	m.String() // "application/json; charset=utf-8"

Строка разбирается в объект MIME типа функцией ParseMime, новый MIME тип
создаётся функцией NewMime:

	m = dic.ParseMime("text/plain; charset=utf-8")
	m = dic.NewMime("application", "json", map[string]string{"charset": "utf-8"})

# HTTP методы

Справочник HTTP методов запросов содержит стандартные и дополнительные методы.
Каждый метод имеет имя и битовую маску, используемую для компактного хранения
наборов методов. Сравнение методов выполняется по имени или по имени и маске:

	m := dic.Method().Get
	m.IsEqual(dic.ParseMethod("get"))     // true
	m.IsEqualFull(dic.Method().Head)      // false

Строка разбирается в объект метода функцией ParseMethod, новый метод создаётся
функцией NewMethod:

	m = dic.NewMethod("FLUSH") // HTTP метод с именем "FLUSH"

# Заголовки

Справочник заголовков содержит предопределённые заголовки HTTP запросов
и ответов с описанием и ссылкой на документ RFC. Сравнение заголовков
выполняется без учёта регистра символов:

	h := dic.Header().ContentType
	h.IsEqual(dic.ParseHeader("content-type")) // true

Строка разбирается в объект заголовка функцией ParseHeader, новый заголовок
создаётся функцией NewHeader.

# Статусы HTTP ответов

Справочник статусов HTTP ответов содержит предопределённые статусы с кодом,
названием и описанием. Статус предоставляет доступ к коду и названию, а так же
сравнение по коду или по коду и названию:

	s := dic.Status().NotFound
	s.Code()                       // 404
	s.IsEqualCode(404)             // true
	s.IsEqual(dic.ParseStatusCode(404)) // true

Строка разбирается в объект статуса функцией ParseStatusString, числовой код —
функцией ParseStatusCode, новый статус создаётся функцией NewStatus.

# MIME типы файлов

Справочник MIME типов расширений имён файлов определяет тип контента по имени
файла, по расширению имени файла или по содержимому:

	f := dic.File()
	f.MimeByFilename("example.txt")  // text/plain
	f.MimeByExtension(".png")        // image/png
	f.MimeByContent(content)         // по первым 512 байтам контента

При инициализации пакета полный справочник типов контента регистрируется
в стандартном пакете mime, поэтому функция MimeByExtension использует как
встроенные типы стандартной библиотеки, так и типы справочника.

# Ошибки

Справочник ошибок предоставляет инструментарий для создания собственных
справочников ошибок с шаблонами, аргументами и числовыми кодами. Ошибка
создаётся функцией NewError, наполняется аргументами методом Bind и
сравнивается по якорю или по коду:

	const errNotFound = "объект %q не найден"

	// myErrors Пользовательский справочник ошибок.
	type myErrors struct {
		dic.Errors
		NotFound dic.IError
	}

	var Errors = &myErrors{
		Errors:   dic.Error(),
		NotFound: dic.NewError(errNotFound, "название объекта"),
	}

	err := Errors.NotFound.Bind("файл конфигурации")
	errors.Is(err, Errors.NotFound)               // true
	errors.Is(err, Errors.NotFound.Bind("другой")) // true, эквивалентность по якорю

Копии ошибок с разными значениями аргументов эквивалентны при сравнении
функцией IsEqual или стандартной функцией errors.Is, так как сравнение
выполняется по якорю — константе ошибки с фиксированным адресом.

Код ошибки назначается через типизированные сеттеры и доступен через
типизированные геттеры для всех целочисленных типов:

	Errors.NotFound.CodeU8().Set(10)
	Errors.NotFound.CodeU8().Get() // 10

Стандартная ошибка разбирается в объект IError функцией ParseError, объект
IError извлекается методом Unbind.

# Дополнение справочников пользовательскими данными

Любой справочник дополняется пользовательскими данными через встраивание:

	// CustomHeader Структура нового справочника с дополнительными пользовательскими заголовками.
	type CustomHeader struct {
		dic.Headers // Встраивание всех уже существующих заголовков.

		MyCustomHeader1    dic.IHeader // Заголовок my-custom/header-1.
		HeaderSecondCustom dic.IHeader // Заголовок header-second/custom.
	}

	var custom = &CustomHeader{
		Headers:            dic.Header(),                          // Подключение всех существующих заголовков.
		MyCustomHeader1:    dic.NewHeader("My-Custom/Header-1"),   // Заголовок my-custom/header-1.
		HeaderSecondCustom: dic.NewHeader("Header-Second/Custom"), // Заголовок header-second/custom.
	}

Полученный справочник принимается всеми функциями библиотеки, принимающими
исходный справочник, например методом ParseError при поиске ошибки
в пользовательском справочнике.

*/

package dic
